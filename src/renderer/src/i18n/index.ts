const DICTS: Record<Lang, Record<string, string>> = { pt, en, es }

const STORAGE_KEY = 'prime-desk:lang'

function detect(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === 'pt' || saved === 'en' || saved === 'es') return saved
  const nav = (navigator.language || 'en').toLowerCase()
  if (nav.startsWith('pt')) return 'pt'
  if (nav.startsWith('es')) return 'es'
  return 'en'
}

let current: Lang = detect()
const listeners = new Set<() => void>()

function subscribe(fn: () => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang): void {
  if (lang === current) return
  current = lang
  localStorage.setItem(STORAGE_KEY, lang)
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang
  for (const fn of listeners) fn()
}

/** Traduz uma chave. `{n}` e afins são substituídos por `vars`. */
export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[current]
  let out = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v))
  }
  return out
}

/** Hook: re-renderiza o componente quando o idioma muda. */
export function useT(): { t: typeof t; lang: Lang } {
  const lang = useSyncExternalStore(subscribe, getLang, getLang)
  return { t, lang }
}
